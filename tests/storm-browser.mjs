import { chromium } from "playwright";
import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
const native = process.env.LEAF_OPTICS_NATIVE === "1";
const browser = await chromium.launch(native ? { channel: "chrome", headless: true } : { headless: true, args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
  const errors = []; page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
  await page.goto(`${process.env.LEAF_BASE_URL || "http://127.0.0.1:5200"}/?testMode=manual&journeyZ=-320${native ? "" : "&forceWebGL"}`);
  await page.waitForFunction(() => window.advanceTime);
  const read = () => page.evaluate(() => JSON.parse(window.render_game_to_text()));
  const initial = await read(); assert.equal(initial.weather.rainSegments, 384);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Play test sound", exact: true }).click();
  await page.waitForFunction(() => JSON.parse(window.render_game_to_text()).audio.state === "running");
  await page.waitForFunction(() => JSON.parse(window.render_game_to_text()).audio.activeEffects === 0);
  await page.getByRole("button", { name: "Back", exact: true }).click();
  const paused = await read();
  await page.evaluate(() => window.advanceTime(5000));
  assert.equal((await read()).time, paused.time, "storm clock advanced in menu");
  await page.getByRole("button", { name: "Resume journey", exact: true }).click();
  await page.evaluate(() => window.advanceTime(3080));
  const flash = await read(); assert.ok(flash.weather.strength > .9);
  await page.screenshot({ path: `output/web-game/storm-flash-${native ? "native" : "webgl2"}.png` });
  await page.evaluate(() => window.advanceTime(1130));
  const thunder = await read(); assert.ok(thunder.audio.activeEffects >= 1, "fixed-step storm did not trigger unlocked thunder");
  await page.waitForFunction(() => JSON.parse(window.render_game_to_text()).audio.activeEffects === 0);
  await page.keyboard.press("Escape");
  const stopped = await read(); await page.evaluate(() => window.advanceTime(30000));
  assert.equal((await read()).time, stopped.time);
  assert.equal((await read()).audio.activeEffects, 0, "paused storm accumulated thunder");
  await page.getByRole("button", { name: "Resume journey", exact: true }).click();
  await page.keyboard.press("r");
  const reset = await read();
  // DEV fixtures deliberately restart at their configured reach.
  assert.equal(reset.weather.strength, initial.weather.strength); assert.equal(reset.time, 0);
  assert.equal(reset.sky.storm, true); assert.equal(reset.sky.transitionActive, false, "restart retained cloud transition");
  assert.equal(reset.physics.fragments, 1);
  assert.equal(reset.weather.allocatedSegments, initial.weather.allocatedSegments);
  await page.goto(process.env.LEAF_BASE_URL || "http://127.0.0.1:5200");
  await page.waitForFunction(() => window.render_game_to_text);
  await page.getByRole("button", { name: "Begin journey", exact: true }).click();
  await page.keyboard.press("r");
  const gameplayReset = await read();
  assert.equal(gameplayReset.weather.rainSegments, 0);
  assert.equal(gameplayReset.journey.id, "headwaters");
  assert.equal(gameplayReset.opening.phase, "falling");
  assert.deepEqual(errors, []);
  await writeFile(`output/web-game/storm-${native ? "native" : "webgl2"}.json`, JSON.stringify({ initial, flash, thunder, reset, errors }, null, 2));
  console.log("Storm rain, unlocked thunder, menu freeze, cleanup and headwaters reset passed");
} finally { await browser.close(); }
